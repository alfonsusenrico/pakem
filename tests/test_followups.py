"""Projects follow Pakem updates (ADR 0017): copies of Pakem files, change notes, alignment."""

from __future__ import annotations

import sys
import tomllib

from support import REPO_ROOT, IsolatedTestCase, git, init_repo, write

sys.path.insert(0, str(REPO_ROOT / "tools"))
from pakem_lib.changelog import check_fragment  # noqa: E402

WORKFLOW = "skills/release-delivery/assets/ci/github/workflows/security.yml"
CONTRACTS = "skills/release-delivery/assets/deploy/contracts.py"
RELEASE = "skills/release-delivery/assets/ci/github/workflows/release.yml"
SECURITY_V1 = "# Pakem CI template: static security checks.\nname: security\n# v1\n"
SECURITY_V2 = "# Pakem CI template: static security checks.\nname: security\n# v2\n"
CONTRACTS_V1 = "#!/usr/bin/env python3\n\"\"\"Contracts.\"\"\"\nVERSION = 1\n"
CONTRACTS_V2 = "#!/usr/bin/env python3\n\"\"\"Contracts.\"\"\"\nVERSION = 2\n"
PROJECT_AGENTS = "# app\n\nCapabilities: none\nDelivery: nobody\n"


class FollowUpTests(IsolatedTestCase):
    def setUp(self) -> None:
        super().setUp()
        init_repo(self.framework, self.home)
        write(self.framework / WORKFLOW, SECURITY_V1)
        write(self.framework / CONTRACTS, CONTRACTS_V1)
        write(self.framework / RELEASE, "# Pakem CI template: publish a release.\nname: release\n")
        self.commit(self.framework, "chore: v1 assets")
        write(self.framework / WORKFLOW, SECURITY_V2)
        write(self.framework / CONTRACTS, CONTRACTS_V2)
        self.commit(self.framework, "feat: v2 assets")

        self.project = init_repo(self.base / "app", self.home)
        write(self.project / "AGENTS.md", PROJECT_AGENTS)

    def commit(self, repo, message: str) -> str:
        git(repo, "add", "-A", home=self.home)
        git(repo, "commit", "-q", "--allow-empty", "-m", message, home=self.home)
        return git(repo, "rev-parse", "HEAD", home=self.home).stdout.strip()

    def check(self) -> str:
        completed = self.pakem("project", "check", str(self.project))
        self.assert_ok(completed)
        return completed.stdout

    def test_copies_are_current_older_or_changed(self) -> None:
        write(self.project / ".github" / "workflows" / "security.yml", SECURITY_V1)
        provenance = "# Copied from Pakem 1234567 (skills/release-delivery/assets/deploy); do not edit here.\n"
        write(self.project / "deploy" / "af" / "contracts.py",
              CONTRACTS_V2.replace("\n", "\n" + provenance, 1))
        write(self.project / ".github" / "workflows" / "verify.yml", "# Pakem CI template: x\nchanged\n")
        # A project's own workflow that only shares a template's file name is not a copy.
        write(self.project / ".github" / "workflows" / "release.yml", "# Generated by dist\nname: Release\n")

        output = self.check()
        self.assertIn(".github/workflows/security.yml is an older copy of Pakem's", output)
        self.assertNotIn("contracts.py", output, "a current copy with a provenance line needs nothing")
        self.assertNotIn("release.yml", output)
        self.assertNotIn("verify.yml", output, "no template of that name exists")

        write(self.project / "deploy" / "af" / "contracts.py", CONTRACTS_V1.replace("1\n", "1  # local\n"))
        self.assertIn("deploy/af/contracts.py differs from every version of Pakem's", self.check())

    def test_templates_recopies_only_older_copies(self) -> None:
        workflow = self.project / ".github" / "workflows" / "security.yml"
        write(workflow, SECURITY_V1)
        provenance = "# Copied from agent-framework d36ea7a (skills/release-delivery/assets/deploy); do not edit here.\n"
        contracts = self.project / "deploy" / "af" / "contracts.py"
        write(contracts, CONTRACTS_V1.replace("\n", "\n" + provenance, 1))

        planned = self.pakem("project", "sync", str(self.project), "--templates")
        self.assert_ok(planned)
        self.assertIn("re-copy .github/workflows/security.yml", planned.stdout)
        self.assertEqual(workflow.read_text(), SECURITY_V1, "a dry run writes nothing")

        contracts.chmod(0o755)
        self.assert_ok(self.pakem("project", "sync", str(self.project), "--templates", "--apply"))
        self.assertEqual(workflow.read_text(), SECURITY_V2)
        self.assertEqual(contracts.stat().st_mode & 0o777, 0o755, "a re-copy keeps the file's permissions")
        lines = contracts.read_text().splitlines()
        self.assertEqual(lines[0], "#!/usr/bin/env python3")
        self.assertRegex(lines[1], r"^# Copied from Pakem [0-9a-f]{7} \(" + CONTRACTS + r"\); do not edit here\.$")
        self.assertIn("VERSION = 2", contracts.read_text())
        self.assertNotIn("copy of Pakem", self.check())

    def test_notes_since_the_aligned_commit(self) -> None:
        write(self.framework / "changes" / "added-runners.md",
              "- Several runners.\n- Projects: make CI safe to run twice\n  at once.\n")
        write(self.framework / "changes" / "fixed-typo.md", "- A typo.\n")
        self.commit(self.framework, "feat: runners")

        output = self.check()
        self.assertIn("Pakem change added-runners: Projects: make CI safe to run twice at once.", output)
        self.assertNotIn("fixed-typo", output, "a fragment without a note asks nothing of projects")

        # A release before the project ever aligned keeps its notes: they live in git.
        (self.framework / "changes" / "added-runners.md").unlink()
        release = self.commit(self.framework, "chore: release")
        self.assertIn("Pakem change added-runners: Projects: make CI safe to run twice at once.", self.check())
        git(self.framework, "revert", "--no-edit", release, home=self.home)

        self.assert_ok(self.pakem("project", "sync", str(self.project), "--aligned", "--apply"))
        record = tomllib.loads((self.project / ".pakem" / "framework.toml").read_text())
        self.assertEqual(record["aligned"], git(self.framework, "rev-parse", "HEAD", home=self.home).stdout.strip())
        self.assertNotIn("Pakem change", self.check())

        # A release consumes the fragment; the next note still reaches the project.
        (self.framework / "changes" / "added-runners.md").unlink()
        self.commit(self.framework, "chore: release")
        write(self.framework / "changes" / "changed-cache.md", "- Cache.\n- Projects: re-copy the workflows.\n")
        self.commit(self.framework, "feat: cache")
        output = self.check()
        self.assertIn("Pakem change changed-cache: Projects: re-copy the workflows.", output)
        self.assertNotIn("added-runners", output)

    def test_a_merged_copy_stays_quiet_until_pakem_changes_it(self) -> None:
        workflow = self.project / ".github" / "workflows" / "security.yml"
        write(workflow, SECURITY_V2 + "# project step\n")
        self.assertIn("differs from every version", self.check())

        self.assert_ok(self.pakem("project", "sync", str(self.project), "--aligned", "--apply"))
        record = tomllib.loads((self.project / ".pakem" / "framework.toml").read_text())
        self.assertIn(".github/workflows/security.yml", record["merged"])
        self.assertNotIn("security.yml", self.check())

        write(self.framework / WORKFLOW, SECURITY_V2 + "# v3\n")
        self.commit(self.framework, "feat: v3")
        self.assertIn("security.yml differs from every version", self.check())

    def test_session_start_names_the_follow_ups(self) -> None:
        write(self.project / ".github" / "workflows" / "security.yml", SECURITY_V1)
        completed = self.pakem("status", "--brief", cwd=self.project)
        self.assertIn("Pakem changes to align here: 1 outdated copy of Pakem files", completed.stdout)
        self.assertIn("`pakem-update`", completed.stdout)


class NoteFormTests(IsolatedTestCase):
    def test_notes_need_their_exact_form_and_a_change(self) -> None:
        good = write(self.base / "changes" / "added-x.md", "- X.\n- Projects: do y.\n")
        self.assertEqual(check_fragment(good)[1], [])
        lower = write(self.base / "changes" / "added-y.md", "- Y.\n- projects: do y.\n")
        self.assertIn("must start with '- Projects: '", " ".join(check_fragment(lower)[1]))
        prose = write(self.base / "changes" / "added-w.md", "- Projects follow updates by themselves.\n")
        self.assertEqual(check_fragment(prose)[1], [], "a change whose first word is Projects is not a note")
        alone = write(self.base / "changes" / "added-z.md", "- Projects: do z.\n")
        self.assertIn("has only a note for projects", " ".join(check_fragment(alone)[1]))

    def test_a_framework_without_git_has_no_follow_ups(self) -> None:
        project = init_repo(self.base / "app", self.home)
        write(project / "AGENTS.md", PROJECT_AGENTS)
        write(project / ".github" / "workflows" / "security.yml", "# Pakem CI template: old\n")
        completed = self.pakem("project", "check", str(project))
        self.assertNotIn("copy of Pakem", completed.stdout)
